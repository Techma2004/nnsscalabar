-- 0/1 flags keep the API output (is_active: 1) identical to the old MySQL build.
DO $$ BEGIN
  CREATE DOMAIN flag AS SMALLINT CHECK (VALUE IN (0, 1));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- MySQL-style ON UPDATE CURRENT_TIMESTAMP: refresh updated_at when a row really
-- changed and the statement did not set updated_at itself.
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

-- results: changing only the grading scale (is_junior, on promotion) is not an edit
-- by the teacher, so it must not bump updated_at (the approval queue sorts on it).
CREATE OR REPLACE FUNCTION touch_results_updated_at() RETURNS trigger AS $$
BEGIN
  IF (to_jsonb(NEW) - 'is_junior' - 'grade' - 'remark' - 'total_score' - 'updated_at')
     = (to_jsonb(OLD) - 'is_junior' - 'grade' - 'remark' - 'total_score' - 'updated_at') THEN
    NEW.updated_at := OLD.updated_at;
  ELSIF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

-- MySQL FIND_IN_SET(needle, 'a,b,c') for the comma separated announcement audience.
CREATE OR REPLACE FUNCTION find_in_set(needle text, hay text) RETURNS integer AS $$
  SELECT COALESCE(
    (SELECT i::int FROM unnest(string_to_array(hay, ',')) WITH ORDINALITY AS t(v, i) WHERE v = needle LIMIT 1), 0)
$$ LANGUAGE sql IMMUTABLE;

