-- 11. RESULTS  (CA 30 = six components of 5, Exam 70; JSS A/C/P/F, SSS WAEC A1-F9)
CREATE TABLE IF NOT EXISTS results (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       INT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject_id       INT NOT NULL REFERENCES subjects(id),
  term_id          INT NOT NULL REFERENCES terms(id),
  teacher_id       INT NOT NULL REFERENCES teachers(id),
  test1_score      NUMERIC(5,2) NULL DEFAULT NULL,
  quiz_score       NUMERIC(5,2) NULL DEFAULT NULL,
  assignment_score NUMERIC(5,2) NULL DEFAULT NULL,
  test2_score      NUMERIC(5,2) NULL DEFAULT NULL,
  project_score    NUMERIC(5,2) NULL DEFAULT NULL,
  note_score       NUMERIC(5,2) NULL DEFAULT NULL,
  ca_score         NUMERIC(5,2) DEFAULT 0,
  exam_score       NUMERIC(5,2) DEFAULT 0,
  is_junior        flag NOT NULL DEFAULT 0,
  total_score      NUMERIC(5,2) GENERATED ALWAYS AS (ca_score + exam_score) STORED,
  grade            VARCHAR(5) GENERATED ALWAYS AS (
    CASE
      WHEN is_junior = 1 THEN
        CASE
          WHEN (ca_score + exam_score) >= 80 THEN 'A'
          WHEN (ca_score + exam_score) >= 60 THEN 'C'
          WHEN (ca_score + exam_score) >= 50 THEN 'P'
          ELSE 'F'
        END
      ELSE
        CASE
          WHEN (ca_score + exam_score) >= 75 THEN 'A1'
          WHEN (ca_score + exam_score) >= 70 THEN 'B2'
          WHEN (ca_score + exam_score) >= 65 THEN 'B3'
          WHEN (ca_score + exam_score) >= 60 THEN 'C4'
          WHEN (ca_score + exam_score) >= 55 THEN 'C5'
          WHEN (ca_score + exam_score) >= 50 THEN 'C6'
          WHEN (ca_score + exam_score) >= 45 THEN 'D7'
          WHEN (ca_score + exam_score) >= 40 THEN 'E8'
          ELSE 'F9'
        END
    END
  ) STORED,
  remark           VARCHAR(20) GENERATED ALWAYS AS (
    CASE
      WHEN is_junior = 1 THEN
        CASE
          WHEN (ca_score + exam_score) >= 80 THEN 'Excellent'
          WHEN (ca_score + exam_score) >= 60 THEN 'Credit'
          WHEN (ca_score + exam_score) >= 50 THEN 'Pass'
          ELSE 'Fail'
        END
      ELSE
        CASE
          WHEN (ca_score + exam_score) >= 75 THEN 'Excellent'
          WHEN (ca_score + exam_score) >= 70 THEN 'Very Good'
          WHEN (ca_score + exam_score) >= 65 THEN 'Good'
          WHEN (ca_score + exam_score) >= 50 THEN 'Credit'
          WHEN (ca_score + exam_score) >= 40 THEN 'Pass'
          ELSE 'Fail'
        END
    END
  ) STORED,
  uploaded_at      TIMESTAMPTZ DEFAULT now(),
  updated_at       TIMESTAMPTZ DEFAULT now(),
  is_approved      flag DEFAULT 0,
  approved_by      INT DEFAULT NULL REFERENCES users(id),
  approved_at      TIMESTAMPTZ DEFAULT NULL,
  rejected_at      TIMESTAMPTZ NULL DEFAULT NULL,
  rejected_by      INT DEFAULT NULL REFERENCES users(id),
  rejection_note   TEXT DEFAULT NULL,
  UNIQUE (student_id, subject_id, term_id),
  CONSTRAINT chk_results_components_v2 CHECK (
    (test1_score      IS NULL OR (test1_score      >= 0 AND test1_score      <= 5)) AND
    (quiz_score       IS NULL OR (quiz_score       >= 0 AND quiz_score       <= 5)) AND
    (assignment_score IS NULL OR (assignment_score >= 0 AND assignment_score <= 5)) AND
    (test2_score      IS NULL OR (test2_score      >= 0 AND test2_score      <= 5)) AND
    (project_score    IS NULL OR (project_score    >= 0 AND project_score    <= 5)) AND
    (note_score       IS NULL OR (note_score       >= 0 AND note_score       <= 5))),
  CONSTRAINT chk_results_scheme_v2 CHECK (ca_score >= 0 AND ca_score <= 30 AND exam_score >= 0 AND exam_score <= 70)
);
CREATE INDEX IF NOT EXISTS idx_results_student  ON results(student_id);
CREATE INDEX IF NOT EXISTS idx_results_term     ON results(term_id);
CREATE INDEX IF NOT EXISTS idx_results_subject  ON results(subject_id);
CREATE INDEX IF NOT EXISTS idx_results_teacher  ON results(teacher_id);
